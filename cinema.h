/* cinema.h — библиотека для каталога онлайн-кинотеатра.
 *
 * Сдаётся один файл .c, который начинается с #include "cinema.h" и реализует все функции ниже.
 * Функции main в нём быть не должно. Функции ничего не печатают и не читают с клавиатуры.
 * Тесты проверяют утечки памяти, незакрытые файлы, двойной free и выход за границы блоков.
 */
#ifndef CINEMA_H
#define CINEMA_H

#include <stdio.h>
#include <stdlib.h>

/* Размер строковых полей фильма (вместе с '\0') */
#define FILM_TEXT 128

/* Фильм */
typedef struct {
    char title[FILM_TEXT];    /* название */
    int year;                 /* год выпуска */
    char country[FILM_TEXT];  /* страна или страны через запятую */
    char genre[FILM_TEXT];    /* жанр или жанры через запятую */
    double rating;            /* рейтинг */
} Film;

/* Элемент двусвязного кольцевого списка фильмов */
typedef struct FilmNode {
    Film film;
    struct FilmNode *prev;  /* предыдущий; у первого — последний */
    struct FilmNode *next;  /* следующий; у последнего — первый */
} FilmNode;

/* Кольцевой список фильмов: каталог или избранное */
typedef struct {
    FilmNode *head;  /* первый фильм, NULL — список пуст */
    int count;       /* количество фильмов */
} FilmList;

/* Пользователь */
typedef struct {
    char login[21];       /* 3..20 латинских букв и цифр */
    char password[21];    /* 6..20 латинских букв и цифр */
    char card[17];        /* номер карты: 16 цифр */
    int favorites_count;  /* размер списка избранного */
    int is_admin;         /* 1 — администратор, 0 — нет */
} User;

/* ---------- Список фильмов ---------- */

/* Инициализирует новый список: в полях структуры может быть мусор, после вызова head == NULL и count == 0.
 * Вызывается один раз перед первым использованием списка. Элементов она не освобождает — для этого list_free */
void list_init(FilmList *list);

/* Добавляет копию фильма в конец списка (новый элемент — через malloc) */
void list_append(FilmList *list, const Film *film);

/* Первый фильм с таким названием или NULL */
FilmNode *list_find(const FilmList *list, const char *title);

/* Удаляет из списка первый фильм с таким названием и освобождает его элемент. Если удалён первый
 * фильм, первым становится следующий. Возвращает 1, если фильм был, иначе 0 */
int list_remove(FilmList *list, const char *title);

/* Освобождает все элементы, список становится пустым */
void list_free(FilmList *list);

/* ---------- Файлы фильмов ---------- */

/* Добавляет в конец списка фильмы из файла (формат films.txt): на каждый фильм пять строк — название,
 * год, страны, жанры, рейтинг (число с точкой). Строки могут заканчиваться как "\n", так и "\r\n",
 * последняя строка файла может быть без перевода строки; пустые строки между фильмами пропускаются.
 * В строковые поля символы перевода строки не попадают. Строки не длиннее 255 байт без учёта перевода строки;
 * из более длинной, чем 127 байт, в поле попадают первые 127 байт. Гарантируется, что файл состоит из полных записей
 * по пять строк, год — целое число, рейтинг — число с точкой; пустые строки бывают только между фильмами, перед первым
 * и после последнего. Возвращает число прочитанных фильмов, если файла нет — -1 */
int films_load(FilmList *list, const char *filename);

/* Записывает список в файл в том же формате: пять строк на фильм, каждая заканчивается "\n",
 * рейтинг — с одной цифрой после точки (printf "%.1f"). Возвращает 1, при ошибке открытия файла — 0 */
int films_save(const FilmList *list, const char *filename);

/* Фильм для добавления в каталог корректен: название, страны и жанры не пустые (длина больше 0), год 1895..2100,
 * рейтинг от 0 до 10 включительно. 1 — да, 0 — нет */
int valid_film(const Film *film);

/* ---------- Пользователи ---------- */

/* Логин: от 3 до 20 символов, только латинские буквы и цифры. 1 — корректен, 0 — нет */
int valid_login(const char *login);

/* Пароль: от 6 до 20 символов, только латинские буквы и цифры, есть хотя бы одна заглавная буква,
 * одна строчная и одна цифра */
int valid_password(const char *password);

/* Номер карты: ровно 16 цифр */
int valid_card(const char *card);

/* Читает пользователей из файла (формат users.txt): по строке на пользователя,
 * "логин пароль карта размер_избранного админ" через пробел, например "anna Qwerty1 1234567812345678 2 0".
 * Строки могут заканчиваться "\n" или "\r\n". Гарантируется, что каждая строка записана в этом формате, а логин,
 * пароль и номер карты удовлетворяют правилам valid_login, valid_password и valid_card.
 * Читает не больше max пользователей. Возвращает их число; если файла нет — 0 */
int users_load(const char *filename, User *users, int max);

/* Записывает пользователей в файл в том же формате (каждая строка заканчивается "\n").
 * Возвращает 1, при ошибке открытия — 0 */
int users_save(const char *filename, const User *users, int n);

/* Номер пользователя с таким логином или -1 (логины сравниваются с учётом регистра: anna и Anna — разные) */
int user_find(const User *users, int n, const char *login);

/* Вход: номер пользователя, если логин есть и пароль совпадает, иначе -1 */
int user_login(const User *users, int n, const char *login, const char *password);

/* Регистрация: добавляет пользователя users[*n] (избранное 0, не админ) и увеличивает *n.
 * Проверки по порядку, возвращается код первой неудачной: 1 — неверный логин, 2 — неверный пароль,
 * 3 — неверная карта, 4 — логин занят, 5 — уже max пользователей. 0 — пользователь добавлен */
int user_register(User *users, int *n, int max, const char *login, const char *password, const char *card);

/* ---------- Избранное ---------- */

/* Имя файла избранного: "favorites_" + логин + ".txt"; out вмещает 35 байт (логин из 20 символов и '\0') */
void favorites_filename(const char *login, char *out);

/* Добавляет копию фильма в конец избранного, если фильма с таким названием там ещё нет.
 * Возвращает 1, если добавлен, 0 — если уже был */
int favorites_add(FilmList *favorites, const Film *film);

/* ---------- Администратор ---------- */

/* Удаляет из каталога первый фильм с таким названием, а затем убирает его из избранного всех n пользователей:
 * у каждого, у кого есть файл избранного, удаляет этот фильм из файла (если он там есть) и ставит favorites_count
 * равным числу фильмов в файле. Пользователи без файла избранного не меняются, новые файлы не создаются.
 * Если фильма с таким названием в каталоге нет, ничего не меняет и возвращает 0; иначе 1 */
int catalog_delete(FilmList *catalog, const char *title, User *users, int n);

#endif
